/**
 * 첫 진입 때 본문이 다 내려올 동안 초록 바탕에 로고를 띄운다.
 * 로고 조각이 뜻대로 모인다 — 별(희망)이 먼저 반짝이고, 두 사람(함께하는 사람들)이 양쪽 아래에서 일어서 별로 손을 뻗고(스스로 서는 힘), 곡선(이어지는 삶)이 아래에서 둘을 감싸 잇는다.
 * 뜬 지 1.5초가 지나고 문서 로드가 끝나면 사라진다. 레이아웃에 붙어 있어 새로고침·직접 접속 때만 뜨고 화면 이동 때는 뜨지 않는다
 */
const IntroSplash = () => {
  // refs
  const splashRef = useRef<HTMLDivElement>(null);
  // states
  const [isLeaving, setIsLeaving] = useState(false);
  const [isDone, setIsDone] = useState(false);
  // handlers
  const handleSplashTransitionEnd = () => {
    setIsDone(true);
  };
  // effects
  useEffect(() => {
    const splash = splashRef.current;
    if (!splash) return;
    let isActive = true;
    const now = performance.now();
    const shownAt = Math.min(
      now,
      ...splash
        .getAnimations({ subtree: true })
        .map(animation => Number(animation.startTime ?? now)),
    );
    const shown = new Promise(resolve => {
      window.setTimeout(resolve, Math.max(0, MIN_SHOW_MS - (now - shownAt)));
    });
    const loaded = new Promise(resolve => {
      if (document.readyState === "complete") {
        resolve(null);
        return;
      }
      window.addEventListener("load", resolve, { once: true });
      window.setTimeout(resolve, MAX_WAIT_MS);
    });
    Promise.all([shown, loaded]).then(() => {
      if (isActive) setIsLeaving(true);
    });
    return () => {
      isActive = false;
    };
  }, []);
  // render
  if (isDone) return null;
  return (
    <div
      ref={splashRef}
      id="intro-splash"
      aria-hidden="true"
      onTransitionEnd={handleSplashTransitionEnd}
      className={cn(
        "fixed inset-0 z-50 grid place-items-center bg-pine transition-opacity duration-500",
        isLeaving && "pointer-events-none opacity-0",
      )}>
      <noscript>
        <style>{"#intro-splash{display:none}"}</style>
      </noscript>
      <svg
        viewBox="0 0 926 1034"
        className="w-32 overflow-visible motion-reduce:**:animate-none md:w-44">
        <g className="origin-center animate-intro-twinkle transform-fill">
          <path
            d={LOGO_PATHS.star}
            className="origin-center animate-intro-star fill-gold transform-fill"
          />
        </g>
        <path
          d={LOGO_PATHS.bigBody}
          className="origin-bottom-left animate-intro-rise fill-paper/92 transform-fill"
        />
        <g className="animate-intro-float-slow transform-fill">
          <path
            d={LOGO_PATHS.bigHead}
            className="animate-intro-drop fill-paper/92 transform-fill"
          />
        </g>
        <g className="animate-intro-float transform-fill">
          <path
            d={LOGO_PATHS.smallBody}
            className="origin-bottom-left animate-intro-reach fill-beige/80 transform-fill"
          />
          <path
            d={LOGO_PATHS.smallHead}
            className="origin-center animate-intro-pop fill-beige/80 transform-fill"
          />
        </g>
        <path
          d={LOGO_PATHS.curve}
          className="origin-left animate-intro-embrace fill-sage/70 transform-fill"
        />
      </svg>
    </div>
  );
};

export default IntroSplash;
